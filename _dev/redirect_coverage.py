#!/usr/bin/env python3
"""Does every old URL land on its real new page? Exits non-zero if not.

    python3 _dev/redirect_coverage.py            offline: simulate the rules
    python3 _dev/redirect_coverage.py -v         also list every URL
    python3 _dev/redirect_coverage.py --live legacymedical.vercel.app
                                                 also request each old
                                                 legacymedicalpalmbeach.com path
                                                 on a deployment and compare

Inputs: _dev/redirects/old-urls.txt (the inventory of old URLs), vercel.json
(rules for legacymedicalpalmbeach.com) and _dev/redirects/cmedjupiter.htaccess
(rules for cmedjupiter.com). Both rule files are generated by build.py, so run
`python3 build.py --check` first.

How each host is simulated:
- legacymedicalpalmbeach.com on Vercel. With "trailingSlash": false Vercel
  strips the slash BEFORE it looks at vercel.json redirects (measured on the
  production deployment 2026-10-14: /yana-shtern/ -> 308 /yana-shtern -> 308
  /dr-yana-shtern). Every WordPress URL ends in a slash, so two permanent hops
  is the expected chain there, not a failure. Query strings carry through.
- cmedjupiter.com on Apache with the .htaccess, then the destination on Vercel.
  The destination must answer directly: one hop in total.

A URL counts as mapped when it ends on a page that exists in public/ (and on
its #fragment, if it has one) within the expected number of hops, and does not
fall through to the home page unless it is one of the few old URLs that had no
real equivalent (theme demo items and an Elementor template; listed below).
"""
import argparse
import json
import os
import re
import subprocess
import sys
import urllib.parse

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
PUB = os.path.join(ROOT, "public")
APEX = "legacymedicalpalmbeach.com"
NO_EQUIVALENT = re.compile(r"^/(wws_portfolio(_category)?|elementor-hf)/")


def ptre(source):
    """Vercel path-to-regexp source -> Python regex (the subset vercel.json uses)."""
    out, i = "", 0
    for m in re.finditer(r"/:(\w+)(\([^)]*\))?(\*)?|:(\w+)(\([^)]*\))", source):
        out += re.escape(source[i:m.start()])
        if m.group(1):
            name, rx, star = m.group(1), m.group(2), m.group(3)
            if star:
                out += "(?:/(?P<%s>.*))?" % name
            else:
                out += "/(?P<%s>%s)" % (name, rx[1:-1] if rx else "[^/]+")
        else:
            out += "(?P<%s>%s)" % (m.group(4), m.group(5)[1:-1])
        i = m.end()
    out += re.escape(source[i:])
    return re.compile(out)


def fill(dest, groups):
    def sub(m):
        return groups.get(m.group(1)) or ""
    return re.sub(r":(\w+)\*?", sub, dest) if "://" not in dest.split(":", 1)[0] else re.sub(r"(?<!https):(\w+)\*?", sub, dest)


class Vercel:
    def __init__(self, cfg):
        self.cfg = cfg
        self.rules = [(r, ptre(r["source"])) for r in cfg["redirects"]]

    def step(self, host, path, query):
        """One request. Returns the redirect target URL, or None if served."""
        if self.cfg.get("trailingSlash") is False and path != "/" and path.endswith("/"):
            return "https://%s%s%s" % (host, path.rstrip("/"), "?" + query if query else "")
        q = dict(urllib.parse.parse_qsl(query, keep_blank_values=True))
        for r, rx in self.rules:
            ok = True
            for h in r.get("has", []):
                if h["type"] == "host":
                    ok = ok and re.fullmatch(h["value"], host) is not None
                elif h["type"] == "query":
                    ok = ok and h["key"] in q and ("value" not in h or re.fullmatch(h["value"], q[h["key"]]) is not None)
                else:
                    ok = False
            if not ok:
                continue
            m = rx.fullmatch(path)
            if m:
                dest = fill(r["destination"], {k: v for k, v in m.groupdict().items() if v is not None})
                if "://" not in dest:
                    dest = "https://%s%s" % (host, dest)
                if query and "?" not in dest:
                    frag = ""
                    if "#" in dest:
                        dest, frag = dest.split("#", 1)
                        frag = "#" + frag
                    dest = dest + "?" + query + frag
                return dest
        return None


class Htaccess:
    def __init__(self, text):
        self.rules, conds = [], []
        for line in text.splitlines():
            line = line.strip()
            if line.startswith("RewriteCond"):
                _, var, rx = line.split(None, 2)
                conds.append((var, re.compile(rx)))
            elif line.startswith("RewriteRule"):
                parts = line.split()
                flags = parts[3].strip("[]").split(",") if len(parts) > 3 else []
                self.rules.append((re.compile(parts[1]), parts[2], conds, "QSD" in flags))
                conds = []

    def step(self, path, query):
        rel = path.lstrip("/")
        for rx, target, conds, qsd in self.rules:
            if all(c.search(query if var == "%{QUERY_STRING}" else "") for var, c in conds) and rx.search(rel):
                if qsd or target.endswith("?"):
                    return target.rstrip("?")
                if not query:
                    return target
                base, _, frag = target.partition("#")
                return base + "?" + query + ("#" + frag if frag else "")
        return None


def served(path, frag):
    """Does public/ serve this path (Vercel cleanUrls), and the #fragment on it?"""
    rel = path.lstrip("/")
    cands = [os.path.join(PUB, "index.html")] if rel == "" else [os.path.join(PUB, rel), os.path.join(PUB, rel + ".html"), os.path.join(PUB, rel, "index.html")]
    f = next((c for c in cands if os.path.isfile(c)), None)
    if not f:
        return False
    if frag:
        return ('id="%s"' % frag) in open(f, encoding="utf-8", errors="ignore").read()
    return True


def resolve(url, vercel, ht):
    hops, u = [], url
    for _ in range(8):
        p = urllib.parse.urlsplit(u)
        host = p.netloc.lower()
        bare = host.replace("www.", "")
        if bare == "cmedjupiter.com":
            nxt = ht.step(p.path or "/", p.query)
        elif bare == APEX:
            nxt = vercel.step(host, p.path or "/", p.query)
        else:
            return hops, u, "off-site"
        if nxt is None:
            return hops, u, None
        hops.append(nxt)
        u = nxt
    return hops, u, "loop"


def live_chain(base, path):
    hops, url = [], "https://%s%s" % (base, path)
    for _ in range(8):
        r = subprocess.run(["curl", "-sS", "-m", "25", "-o", "/dev/null", "-w", "%{http_code} %{redirect_url}", url], capture_output=True, text=True).stdout.split(" ", 1)
        code, loc = r[0], (r[1].strip() if len(r) > 1 else "")
        if code.startswith("3") and loc:
            hops.append(code)
            url = loc
        else:
            return hops, code, url
    return hops, "loop", url


def shortlink_targets():
    """{host: {post id: new path}} for both old hosts, from redirects.py."""
    sys.path.insert(0, ROOT)
    import redirects as R
    return {APEX: R.shortlink_map(APEX, {**R.MAIN, **R.post_map(APEX)}),
            "cmedjupiter.com": R.shortlink_map("cmedjupiter.com", {**R.CMED, **R.post_map("cmedjupiter.com")})}


SHORT = {}


def main():
    SHORT.update(shortlink_targets())
    ap = argparse.ArgumentParser()
    ap.add_argument("-v", action="store_true")
    ap.add_argument("--live", metavar="HOST", help="also test each legacymedicalpalmbeach.com path on this deployment host")
    a = ap.parse_args()
    vercel = Vercel(json.load(open(os.path.join(ROOT, "vercel.json"))))
    ht = Htaccess(open(os.path.join(ROOT, "_dev", "redirects", "cmedjupiter.htaccess")).read())
    inv = [l.split("\t") for l in open(os.path.join(ROOT, "_dev", "redirects", "old-urls.txt")) if l.strip() and not l.startswith("#")]
    ok, bad, by_host = 0, [], {}
    for url, src in ((u.strip(), s.strip()) for u, s in inv):
        p = urllib.parse.urlsplit(url)
        host = p.netloc.replace("www.", "")
        hops, final, err = resolve(url, vercel, ht)
        f = urllib.parse.urlsplit(final)
        fpath = f.path or "/"
        limit = 1 if host == "cmedjupiter.com" else (2 if (p.path.endswith("/") and p.path != "/") else 1)
        problems = []
        if err:
            problems.append(err)
        if f.netloc.replace("www.", "") != APEX or f.netloc.startswith("www."):
            problems.append("ends on %s" % f.netloc)
        if not served(fpath, f.fragment):
            problems.append("404: %s%s" % (fpath, "#" + f.fragment if f.fragment else ""))
        if len(hops) > limit:
            problems.append("%d hops" % len(hops))
        is_home = (p.path in ("", "/") and not p.query) or (p.query and fpath == "/" and not hops)
        if fpath == "/" and not f.fragment and not is_home and not NO_EQUIVALENT.match(p.path) and "p" not in urllib.parse.parse_qs(p.query):
            problems.append("falls through to the home page")
        # A same-host shortlink is served by "/" directly (no rule, so no loop)
        # only when its page has no other equivalent; anything else must redirect.
        pid = urllib.parse.parse_qs(p.query).get("p")
        if pid:
            want = SHORT.get(host, {}).get(int(pid[0]))
            if want is None:
                problems.append("shortlink ID not in redirects.SHORTLINKS")
            elif want.split("#")[0] != fpath:
                problems.append("shortlink lands on %s instead of %s" % (fpath, want))
        h = by_host.setdefault(host, [0, 0])
        h[1] += 1
        if problems:
            bad.append((url, src, hops, problems))
        else:
            ok += 1
            h[0] += 1
        if a.v:
            print("%-4s %-100s -> %s%s [%d]" % ("ok" if not problems else "FAIL", url, fpath, "#" + f.fragment if f.fragment else "", len(hops)))
    for url, src, hops, problems in bad:
        print("FAIL %s (%s): %s; chain: %s" % (url, src, "; ".join(problems), " -> ".join(hops) or "none"))
    for host, (k, n) in sorted(by_host.items()):
        print("%s: %d/%d mapped" % (host, k, n))
    print("redirect coverage: %d/%d mapped" % (ok, len(inv)))
    rc = 1 if bad else 0
    if a.live:
        mism = 0
        for url, _ in ((u.strip(), s) for u, s in inv):
            p = urllib.parse.urlsplit(url)
            if p.netloc.replace("www.", "") != APEX:
                continue
            path = p.path + ("?" + p.query if p.query else "")
            hops, final_code, final_url = live_chain(a.live, path)
            exp = resolve(url, vercel, ht)[1]
            e, g = urllib.parse.urlsplit(exp), urllib.parse.urlsplit(final_url)
            match = final_code == "200" and e.path.rstrip("/") == g.path.rstrip("/") and len(hops) == len(resolve(url, vercel, ht)[0])
            if not match:
                mism += 1
            if a.v or not match:
                print("live %-4s %-70s %s %s -> %s" % ("ok" if match else "DIFF", path, " ".join(hops), final_code, g.path))
        print("live check on %s: %d mismatch(es)" % (a.live, mism))
        rc = rc or (1 if mism else 0)
    sys.exit(rc)


if __name__ == "__main__":
    main()
